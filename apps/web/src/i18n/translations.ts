const AUDIT_PREFIX_EN: [string, string][] = [
  ['Avertissement créé : ', 'Warning created: '],
  ['Cotisation enregistrée ', 'Contribution recorded '],
  ['Écriture comptable : ', 'Accounting entry: '],
  ['Rôle panel changé → ', 'Panel role changed → '],
]

export function translateAuditAction(action: string, locale: Locale): string {
  if (locale === 'fr') return AUDIT_EXACT_FR[action] ?? action
  const exact = AUDIT_EXACT_EN[action]
  if (exact) return exact
  for (const [prefix, replacement] of AUDIT_PREFIX_EN) {
    if (action.startsWith(prefix)) return replacement + action.slice(prefix.length)
  }
  const syncMatch = action.match(/^Sync grades depuis Discord \((\d+) membres scannés\)$/)
  if (syncMatch) return `Grade sync from Discord (${syncMatch[1]} members scanned)`
  return action
}
